//! # Tray Menu Module
//!
//! The system tray menu and the menu bar icon for Juno.
//!
//! ## Menu bar icon
//! The icon is a five-bar waveform shipped as a macOS template image (black plus
//! alpha), so the system tints it for the light or dark menu bar and any
//! wallpaper. State lives in the shape, never in color:
//! - Idle: low bars, hotkey ready
//! - Armed: raised bars, always-listening is on and the mic is open
//! - Recording: bars animate while the mic captures speech
//! - Transcribing: three typing dots cycle while audio becomes text
//! - Agent: a shell prompt with a blinking cursor while the agent runs
//! - Error: bars with an exclamation mark, static so it stays readable
//! - Paused: idle bars at 42% opacity, the macOS convention for disabled
//!
//! Frames live in `icons/tray/waveform/` and are generated by
//! `scripts/gen-tray-icons.py`. The tray-icon crate always draws the image
//! 18 pt tall, so every frame is one 36 px PNG (2x).

