/// Embed one waveform frame from `icons/tray/waveform/`.
macro_rules! tray_frame {
    ($name:literal) => {
        include_bytes!(concat!("../../icons/tray/waveform/", $name, ".png"))
    };
}

const FRAMES_IDLE: &[&[u8]] = &[tray_frame!("idle")];
const FRAMES_ARMED: &[&[u8]] = &[tray_frame!("armed")];
const FRAMES_RECORDING: &[&[u8]] = &[
    tray_frame!("recording-0"),
    tray_frame!("recording-1"),
    tray_frame!("recording-2"),
    tray_frame!("recording-3"),
    tray_frame!("recording-4"),
    tray_frame!("recording-5"),
    tray_frame!("recording-6"),
    tray_frame!("recording-7"),
];
const FRAMES_TRANSCRIBING: &[&[u8]] = &[
    tray_frame!("transcribing-0"),
    tray_frame!("transcribing-1"),
    tray_frame!("transcribing-2"),
    tray_frame!("transcribing-3"),
    tray_frame!("transcribing-4"),
    tray_frame!("transcribing-5"),
];
const FRAMES_AGENT: &[&[u8]] = &[tray_frame!("agent-0"), tray_frame!("agent-1")];
const FRAMES_ERROR: &[&[u8]] = &[tray_frame!("error")];
const FRAMES_PAUSED: &[&[u8]] = &[tray_frame!("paused")];

/// What the menu bar icon is showing. Higher priority states win when several
/// are true at once; see `determine_current_state`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrayIconState {
    /// Hotkey ready, nothing happening
    Idle,
    /// Always-listening is on: the mic is open but nothing has been heard yet
    Armed,
    /// The mic is capturing speech
    Recording,
    /// Audio is being turned into text, or the agent is about to start
    Transcribing,
    /// The agent is executing on the Mac
    Agent,
    /// Something needs the person: mic denied, model missing, agent failed
    Error,
    /// Dictation turned off by the person
    Paused,
}

impl TrayIconState {
    /// PNG frames for this state. One frame means static.
    fn frames(self) -> &'static [&'static [u8]] {
        match self {
            TrayIconState::Idle => FRAMES_IDLE,
            TrayIconState::Armed => FRAMES_ARMED,
            TrayIconState::Recording => FRAMES_RECORDING,
            TrayIconState::Transcribing => FRAMES_TRANSCRIBING,
            TrayIconState::Agent => FRAMES_AGENT,
            TrayIconState::Error => FRAMES_ERROR,
            TrayIconState::Paused => FRAMES_PAUSED,
        }
    }

    /// Time between frames for animated states.
    ///
    /// Every interval is a whole number of display frames at both 60 Hz and
    /// 120 Hz, so a frame always goes up on the same phase of the refresh
    /// cycle. An interval that lands between two refreshes walks across them
    /// and the spacing visibly alternates, which reads as a stutter.
    fn frame_interval(self) -> Duration {
        match self {
            TrayIconState::Recording => Duration::from_millis(100),
            TrayIconState::Transcribing => Duration::from_millis(150),
            TrayIconState::Agent => Duration::from_millis(500),
            _ => Duration::ZERO,
        }
    }

    /// The state word shown in the tray menu.
    pub fn label(self) -> &'static str {
        match self {
            TrayIconState::Idle => "Ready",
            TrayIconState::Armed => "Listening",
            TrayIconState::Recording => "Recording",
            TrayIconState::Transcribing => "Transcribing",
            TrayIconState::Agent => "Agent running",
            TrayIconState::Error => "Needs attention",
            TrayIconState::Paused => "Paused",
        }
    }

    /// Whether the icon is showing Juno at work: a mic open, words becoming
    /// text, or a run. The tray's talk row offers Cancel for these.
    pub fn is_busy(self) -> bool {
        matches!(
            self,
            TrayIconState::Recording | TrayIconState::Transcribing | TrayIconState::Agent
        )
    }

    /// Tooltip for the menu bar icon.
    fn tooltip(self) -> String {
        format!("{} · {}", crate::demo::display_name(), self.label())
    }
}

/// Tray icon manager for handling dynamic icon changes
pub struct TrayIconManager {
    tray_icon: Option<TrayIcon<tauri::Wry>>,
    status_item: Option<MenuItem<tauri::Wry>>,
    /// The chat row, kept so its text can follow what is on screen.
    chat_toggle_item: Option<MenuItem<tauri::Wry>>,
    /// The surface the chat row is currently offering to act on, read as the
    /// pointer reached the icon. Taken by the click it was read for.
    pending_chat_surface: Option<ChatSurface>,
    /// What the Show/Hide Juno row is offering, read with the surface.
    pending_juno_row: Option<JunoRow>,
    /// The Talk to Juno / Cancel row, kept so its text can follow her state.
    talk_item: Option<MenuItem<tauri::Wry>>,
    /// Whether the talk row is offering Cancel, read as the pointer arrived.
    pending_busy: Option<bool>,
    current_state: TrayIconState,
    /// Bumped on every state change. A running animation loop stops as soon as
    /// it sees a generation other than the one it was started with.
    animation_generation: u64,
}

#[allow(clippy::new_without_default)]
impl TrayIconManager {
    pub fn new() -> Self {
        Self {
            tray_icon: None,
            status_item: None,
            chat_toggle_item: None,
            pending_chat_surface: None,
            pending_juno_row: None,
            talk_item: None,
            pending_busy: None,
            current_state: TrayIconState::Idle,
            animation_generation: 0,
        }
    }

    /// Update the tray icon to reflect the current state
    pub async fn update_icon_state(
        &mut self,
        new_state: TrayIconState,
    ) -> Result<(), Box<dyn std::error::Error>> {
        if self.current_state == new_state {
            debug!("Tray icon state unchanged: {:?}", new_state);
            return Ok(());
        }

        info!(
            "🔄 Updating tray icon state: {:?} -> {:?}",
            self.current_state, new_state
        );

        // Stop whatever animation is running before the first frame goes up.
        self.animation_generation = self.animation_generation.wrapping_add(1);

        let Some(tray_icon) = &self.tray_icon else {
            warn!("No tray icon available to update");
            return Ok(());
        };

        let frames = new_state.frames();
        let first = frames.first().ok_or("tray icon state has no frames")?;
        apply_tray_frame(tray_icon, load_tray_icon_from_data(first)?)?;
        tray_icon.set_tooltip(Some(new_state.tooltip()))?;
        if let Some(item) = &self.status_item {
            item.set_text(new_state.label())?;
        }
        // An open menu follows along: the talk row turns into Cancel the
        // moment Juno gets busy, and the click acts on what it then says.
        if let Some(item) = &self.talk_item {
            let busy = new_state.is_busy();
            item.set_text(talk_label(busy))?;
            self.pending_busy = Some(busy);
        }

        self.current_state = new_state;

        if frames.len() > 1 {
            spawn_animation(tray_icon.clone(), new_state, self.animation_generation);
        }

        info!("✅ Tray icon updated successfully");
        Ok(())
    }

    /// Set the tray icon reference
    pub fn set_tray_icon(&mut self, tray_icon: TrayIcon<tauri::Wry>) {
        self.tray_icon = Some(tray_icon);
    }

    /// Show or hide the menu-bar icon. Inert when no tray icon exists yet.
    pub fn set_visible(&self, visible: bool) {
        let Some(tray_icon) = &self.tray_icon else {
            warn!("No tray icon available to show or hide");
            return;
        };
        if let Err(e) = tray_icon.set_visible(visible) {
            warn!("[TrayIcon] Failed to set visibility to {}: {}", visible, e);
        }
    }

    /// Set the disabled menu row that shows the state word
    pub fn set_status_item(&mut self, item: MenuItem<tauri::Wry>) {
        self.status_item = Some(item);
    }

    /// Set the menu row that shows or hides the chat
    pub fn set_chat_toggle_item(&mut self, item: MenuItem<tauri::Wry>) {
        self.chat_toggle_item = Some(item);
    }

    /// Set the Talk to Juno / Cancel row
    pub fn set_talk_item(&mut self, item: MenuItem<tauri::Wry>) {
        self.talk_item = Some(item);
    }

    /// Get the current tray icon state
    pub fn current_state(&self) -> &TrayIconState {
        &self.current_state
    }
}

/// Put one frame on the menu bar, icon and template flag together.
///
/// Setting an icon clears template mode, so the flag has to travel with every
/// icon. It has to travel *with* it, though, not after it: `set_icon` and
/// `set_icon_as_template` are two separate hops to the main thread, and each
/// one assigns the button image, so AppKit can draw the untinted black pixels
/// in between. That half-drawn frame is the flicker, and at ten frames a
/// second it reads as the icon flashing. The combined call assigns the image
/// once, already marked as a template. On Windows and Linux, where there is no
/// such flag, it falls through to a plain `set_icon`.
fn apply_tray_frame(tray_icon: &TrayIcon<tauri::Wry>, image: TauriImage<'_>) -> tauri::Result<()> {
    tray_icon.set_icon_with_as_template(Some(image), true)
}

/// One frame decoded to raw RGBA, so a running animation never has to touch a
/// PNG decoder again.
struct DecodedFrame {
    rgba: Vec<u8>,
    width: u32,
    height: u32,
}

impl DecodedFrame {
    fn decode(icon_data: &[u8]) -> Result<Self, Box<dyn std::error::Error>> {
        let loaded_image = image::load_from_memory(icon_data)?;
        let width = loaded_image.width();
        let height = loaded_image.height();
        Ok(Self {
            rgba: loaded_image.to_rgba8().into_raw(),
            width,
            height,
        })
    }

    fn image(&self) -> TauriImage<'_> {
        TauriImage::new(&self.rgba, self.width, self.height)
    }
}

/// Cycle an animated state's frames until the manager moves to another
/// generation. Frame 0 is already showing when this starts.
fn spawn_animation(tray_icon: TrayIcon<tauri::Wry>, state: TrayIconState, generation: u64) {
    tauri::async_runtime::spawn(async move {
        let interval = state.frame_interval();
        if interval.is_zero() {
            return;
        }

        // Decode every frame up front. Decoding inside the loop put a variable
        // slice of work between the tick and the icon going up, so the frames
        // reached the menu bar unevenly even though the sleep was constant.
        let mut frames = Vec::with_capacity(state.frames().len());
        for (index, data) in state.frames().iter().enumerate() {
            match DecodedFrame::decode(data) {
                Ok(frame) => frames.push(frame),
                Err(e) => {
                    warn!("Tray animation frame {index} for {state:?} failed to decode: {e}");
                    return;
                }
            }
        }
        if frames.len() < 2 {
            return;
        }

        // A fixed-rate ticker rather than sleep-then-work, so the lock wait and
        // the hop to the main thread are absorbed by the interval instead of
        // being added to it. A late tick is delayed rather than fired at once:
        // catching up in a burst would put two frames on the menu bar back to
        // back, which is the double redraw this is meant to avoid.
        let mut ticker = tokio::time::interval_at(tokio::time::Instant::now() + interval, interval);
        ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);

        let mut index = 1usize;
        loop {
            ticker.tick().await;

            let Some(frame) = frames.get(index) else {
                break;
            };

            // Check the generation and draw under the same lock the state
            // change holds. Checking and then releasing let a loop that was
            // already past its check paint a stale frame on top of the icon the
            // new state had just put up, so every transition out of an animated
            // state could show one frame of the old shape.
            let manager = get_tray_icon_manager().await;
            let guard = manager.lock().await;
            if guard.animation_generation != generation {
                break;
            }
            if let Err(e) = apply_tray_frame(&tray_icon, frame.image()) {
                warn!("Tray animation frame {index} for {state:?} failed to apply: {e}");
                break;
            }
            drop(guard);

            index = (index + 1) % frames.len();
        }
    });
}

/// Global tray icon manager
static TRAY_ICON_MANAGER: TokioMutex<Option<Arc<TokioMutex<TrayIconManager>>>> =
    TokioMutex::const_new(None);

/// Get or create the tray icon manager
async fn get_tray_icon_manager() -> Arc<TokioMutex<TrayIconManager>> {
    let mut manager_guard = TRAY_ICON_MANAGER.lock().await;
    if let Some(manager) = manager_guard.as_ref() {
        manager.clone()
    } else {
        let new_manager = Arc::new(TokioMutex::new(TrayIconManager::new()));
        *manager_guard = Some(new_manager.clone());
        new_manager
    }
}

/// The state the menu bar icon is showing right now
pub async fn current_tray_icon_state() -> TrayIconState {
    let manager = get_tray_icon_manager().await;
    let guard = manager.lock().await;
    *guard.current_state()
}

/// Show or hide the menu-bar icon to match the "Show system tray icon" setting.
pub async fn set_tray_icon_visible_now(visible: bool) {
    let manager = get_tray_icon_manager().await;
    let guard = manager.lock().await;
    guard.set_visible(visible);
}

/// The saved "show tray icon" preference, defaulting to shown when it cannot
/// be read: an icon that quietly vanished is the worse surprise.
pub async fn read_tray_icon_visible(app: &AppHandle) -> bool {
    let manager = match crate::settings::manager::SettingsManager::new(app.clone()) {
        Ok(manager) => manager,
        Err(e) => {
            warn!("[TrayIcon] Failed to open settings: {}", e);
            return true;
        }
    };
    match manager.get_agent_settings().await {
        Ok(settings) => settings.show_tray_icon,
        Err(e) => {
            warn!("[TrayIcon] Failed to read the tray icon setting: {}", e);
            true
        }
    }
}

/// Load tray icon from embedded data
fn load_tray_icon_from_data(
    icon_data: &[u8],
) -> Result<TauriImage<'static>, Box<dyn std::error::Error>> {
    let frame = DecodedFrame::decode(icon_data)?;
    Ok(TauriImage::new_owned(frame.rgba, frame.width, frame.height))
}

/// The tray menu plus the two rows whose text changes: the disabled first row
/// that shows the state word, and the chat row that says what it will do.
pub struct TrayMenu {
    pub menu: tauri::menu::Menu<tauri::Wry>,
    pub status_item: MenuItem<tauri::Wry>,
    pub chat_toggle_item: MenuItem<tauri::Wry>,
    pub talk_item: MenuItem<tauri::Wry>,
}

/// What the chat row should say about the surface it is going to act on.
///
/// The pane case stays a single "Show/Hide" on purpose. Rust knows whether the
/// full-size window is up, because Rust is what puts it up, but whether the
/// bar's pane is open or collapsed to the idle pill is the bar's own state and
/// is not reported back here. Naming a direction we cannot know would be a
/// label that is wrong half the time, which is the thing being fixed.
fn chat_toggle_label(surface: ChatSurface) -> &'static str {
    match surface {
        ChatSurface::MainWindow { frontmost: true } => "Hide Chat",
        ChatSurface::MainWindow { frontmost: false } => "Bring Chat to Front",
        ChatSurface::BarPane => "Show/Hide Chat",
    }
}

/// What the tray's one Show/Hide row will do. It used to be two rows, Show/Hide
/// Chat and Show/Hide Floating Bar, which for the bar looks were the same
/// thing said twice, and a "Show/Hide" label never says which.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum JunoRow {
    /// The full-size chat window is in front: put it away.
    HideChat,
    /// The full-size chat window is up but behind something: bring it back.
    BringChatForward,
    /// The floating bar is on screen: take Juno off the screen.
    HideJuno,
    /// The floating bar is hidden: put it back.
    ShowJuno,
}

impl JunoRow {
    pub fn label(self) -> &'static str {
        match self {
            JunoRow::HideChat => "Hide Chat",
            JunoRow::BringChatForward => "Bring Chat to Front",
            JunoRow::HideJuno => "Hide Juno",
            JunoRow::ShowJuno => "Show Juno",
        }
    }
}

/// The row for what is on screen. The chat window wins while it is up: it is
/// the Juno the person is looking at.
pub fn juno_row(surface: ChatSurface, bar_visible: bool) -> JunoRow {
    match surface {
        ChatSurface::MainWindow { frontmost: true } => JunoRow::HideChat,
        ChatSurface::MainWindow { frontmost: false } => JunoRow::BringChatForward,
        ChatSurface::BarPane if bar_visible => JunoRow::HideJuno,
        ChatSurface::BarPane => JunoRow::ShowJuno,
    }
}

/// The talk row's text: one action at a time, never both. Busy means anything
/// Escape would stop (`something_to_stop`): a turn, a dictation, a reply being
/// spoken.
pub fn talk_label(busy: bool) -> &'static str {
    if busy {
        "Cancel"
    } else {
        "Talk to Juno"
    }
}

fn bar_visible(app: &AppHandle) -> bool {
    crate::window_management::WindowManager::is_window_visible(
        app,
        crate::constants::ui::window_labels::FLOATING_BAR,
    )
}

/// Bring the talk row up to date with whether Juno is busy, and remember what
/// it offered for the click.
async fn refresh_talk_row(app: &AppHandle) {
    let busy = crate::commands::escape_key_coordinator::something_to_stop(app).await;
    let manager = get_tray_icon_manager().await;
    let mut guard = manager.lock().await;
    guard.pending_busy = Some(busy);
    if let Some(item) = &guard.talk_item {
        if let Err(e) = item.set_text(talk_label(busy)) {
            warn!("Could not update the tray talk row: {e}");
        }
    }
}

/// Read what is on screen, say so in the chat row, and remember the answer for
/// the click that is probably coming.
///
/// Reading and acting are deliberately separated. Opening a menu puts AppKit
/// into its own tracking loop, and whether the chat window still counts as the
/// focused one while that loop runs is not something to bet the behaviour on.
/// What matters is which window was in front of the person when they reached
/// for the menu bar, and that is this moment, so it is taken once here and used
/// by whatever they click. It also means the row cannot promise one thing and
/// then do another.
async fn refresh_chat_toggle_label(app: &AppHandle) {
    let surface = active_chat_surface(app);
    let row = juno_row(surface, bar_visible(app));
    let manager = get_tray_icon_manager().await;
    let mut guard = manager.lock().await;
    guard.pending_chat_surface = Some(surface);
    guard.pending_juno_row = Some(row);
    if let Some(item) = &guard.chat_toggle_item {
        if let Err(e) = item.set_text(row.label()) {
            warn!("Could not update the tray chat row: {e}");
        }
    }
}

/// Act on what the Show/Hide Juno row is currently offering. Falls back to
/// reading it now if nothing has been read yet.
async fn toggle_juno_from_tray(app: &AppHandle) {
    let row = {
        let manager = get_tray_icon_manager().await;
        let mut guard = manager.lock().await;
        guard.pending_chat_surface = None;
        guard.pending_juno_row.take()
    };
    let row = row.unwrap_or_else(|| juno_row(active_chat_surface(app), bar_visible(app)));
    match row {
        JunoRow::HideChat => {
            crate::window_management::toggle_chat_surface(
                app,
                ChatSurface::MainWindow { frontmost: true },
            )
            .await
        }
        JunoRow::BringChatForward => {
            crate::window_management::toggle_chat_surface(
                app,
                ChatSurface::MainWindow { frontmost: false },
            )
            .await
        }
        // The same toggle Cmd+B makes, which also keeps the bar away while
        // setup is open.
        JunoRow::HideJuno | JunoRow::ShowJuno => {
            if let Err(e) = app.emit(events::menu::TOGGLE_FLOATING_BAR_REQUESTED, ()) {
                warn!("Could not toggle the floating bar: {e}");
            }
        }
    }
    refresh_chat_toggle_label(app).await;
}

/// Talk to Juno, or cancel what she is doing: whichever the row offered.
async fn talk_or_cancel_from_tray(app: &AppHandle) {
    let busy = {
        let manager = get_tray_icon_manager().await;
        let mut guard = manager.lock().await;
        guard.pending_busy.take()
    };
    let busy = match busy {
        Some(busy) => busy,
        None => crate::commands::escape_key_coordinator::something_to_stop(app).await,
    };
    if busy {
        // Exactly what Escape does: stop the newest work, end at rest.
        crate::commands::ui_commands::bar_escape_to_idle(app, "tray cancel").await;
    } else if crate::window_management::onboarding_is_open(app) {
        // Nothing listens during setup, the same as a trigger press.
        crate::window_management::bring_onboarding_forward(app);
    } else if let Err(e) = crate::agent_monitor::agent_voice(app.clone(), "start".into()).await {
        error!("{} could not start talking: {e}", prefixes::TRAY_MENU);
    }
    refresh_talk_row(app).await;
}

/// Act on the chat surface the row is currently offering.
///
/// Falls back to reading it now if nothing has been read yet, so a click that
/// arrives without the pointer ever having been seen still does something
/// sensible.
async fn toggle_chat_from_tray(app: &AppHandle) {
    let surface = {
        let manager = get_tray_icon_manager().await;
        let mut guard = manager.lock().await;
        guard.pending_chat_surface.take()
    };
    let surface = surface.unwrap_or_else(|| active_chat_surface(app));
    crate::window_management::toggle_chat_surface(app, surface).await;
    refresh_chat_toggle_label(app).await;
}

/// The tray icon's click: one rung up, from what was on screen as the pointer
/// arrived (see `toggle_chat_from_tray`).
async fn climb_from_tray(app: &AppHandle) {
    let surface = {
        let manager = get_tray_icon_manager().await;
        let mut guard = manager.lock().await;
        guard.pending_chat_surface.take()
    };
    let surface = surface.unwrap_or_else(|| active_chat_surface(app));
    crate::window_management::climb_chat_ladder(app, surface).await;
    refresh_chat_toggle_label(app).await;
}

/// Get keyboard shortcuts from app state
fn get_keyboard_shortcuts(
    app: &AppHandle,
) -> Result<crate::state::KeyboardShortcuts, Box<dyn std::error::Error>> {
    let app_state = app.state::<AppState>();
    app_state
        .get_keyboard_shortcuts()
        .map_err(|e| format_error(templates::FAILED_TO_RETRIEVE, "keyboard shortcuts", e).into())
}

/// One row of a native menu, described as data so the lists can be tested
/// without an app handle.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RowSpec {
    pub id: &'static str,
    pub label: String,
    /// Only ever an accelerator the app menu really binds. A trigger such as
    /// "hold Fn" cannot be an NSMenu accelerator, so those rows show none.
    pub accelerator: Option<&'static str>,
    pub enabled: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MenuEntry {
    Separator,
    Row(RowSpec),
}

fn row(id: &'static str, label: impl Into<String>, accelerator: Option<&'static str>) -> MenuEntry {
    MenuEntry::Row(RowSpec {
        id,
        label: label.into(),
        accelerator,
        enabled: true,
    })
}

fn quit_label() -> String {
    format!("Quit {}", crate::demo::display_name())
}

/// The tray menu. The talk row is "Talk to Juno" while she is idle and
/// "Cancel" while she is busy, never both, with no accelerator, because
/// triggers are gestures now (see `triggers/mod.rs`) and a menu cannot say
/// "hold Fn". Dictation has no row: it needs the target app to hold focus and
/// only its trigger can say when to stop. Show/Hide Juno is one row for the
/// bar and the chat window both (`JunoRow`).
pub fn tray_menu_spec(juno_label: &str, busy: bool) -> Vec<MenuEntry> {
    let mut entries = vec![
        MenuEntry::Row(RowSpec {
            id: tray_menu_ids::STATUS,
            label: TrayIconState::Idle.label().to_string(),
            accelerator: None,
            enabled: false,
        }),
        MenuEntry::Separator,
        row(tray_menu_ids::TALK, talk_label(busy), None),
        row(tray_menu_ids::NEW_CHAT, "New Chat", Some("CmdOrCtrl+N")),
        MenuEntry::Separator,
        row(tray_menu_ids::SHOW_HIDE, juno_label, None),
        row(
            tray_menu_ids::CENTER_FLOATING_BAR,
            "Center Floating Bar",
            None,
        ),
        MenuEntry::Separator,
        row(tray_menu_ids::SETTINGS, "Settings...", Some("CmdOrCtrl+,")),
        MenuEntry::Separator,
        row(tray_menu_ids::QUIT, quit_label(), Some("CmdOrCtrl+Q")),
    ];
    if super::SHOW_DEVELOPER_MENUS {
        let at = entries
            .iter()
            .position(|entry| matches!(entry, MenuEntry::Row(r) if r.id == tray_menu_ids::SETTINGS))
            .map_or(entries.len(), |i| i - 1);
        entries.insert(
            at,
            row(
                tray_menu_ids::DEVELOPER_TOOLS,
                "Developer Tools",
                Some("CmdOrCtrl+Alt+I"),
            ),
        );
    }
    entries
}

