type BuiltMenu = (
    tauri::menu::Menu<tauri::Wry>,
    Vec<(String, MenuItem<tauri::Wry>)>,
);

/// Build a native menu from a spec. Returns the menu and every item by id.
fn build_menu_from_spec(
    app: &AppHandle,
    spec: &[MenuEntry],
) -> Result<BuiltMenu, Box<dyn std::error::Error>> {
    build_menu_with_edit_items(app, &[], spec)
}

/// The same, led by AppKit's own text items and a separator when there are any.
fn build_menu_with_edit_items(
    app: &AppHandle,
    edit: &[EditItem],
    spec: &[MenuEntry],
) -> Result<BuiltMenu, Box<dyn std::error::Error>> {
    let mut builder = MenuBuilder::new(app);
    for item in edit {
        builder = match item {
            EditItem::Cut => builder.cut(),
            EditItem::Copy => builder.copy(),
            EditItem::Paste => builder.paste(),
            EditItem::SelectAll => builder.select_all(),
        };
    }
    if !edit.is_empty() {
        builder = builder.separator();
    }
    let mut items = Vec::new();
    for entry in spec {
        match entry {
            MenuEntry::Separator => builder = builder.separator(),
            MenuEntry::Row(r) => {
                let mut item = MenuItemBuilder::new(&r.label).id(r.id).enabled(r.enabled);
                if let Some(accel) = r.accelerator {
                    item = item.accelerator(accel);
                }
                let item = item.build(app)?;
                builder = builder.item(&item);
                items.push((r.id.to_string(), item));
            }
        }
    }
    Ok((builder.build()?, items))
}

/// The Mac text items a right-click on the bar starts with, from what was
/// under the pointer: in a text box, Cut, Copy, Paste and Select All; on
/// selected text that cannot be edited, Copy. Anywhere else, none.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EditItem {
    Cut,
    Copy,
    Paste,
    SelectAll,
}

pub fn edit_items_for(editable: bool, has_selection: bool) -> Vec<EditItem> {
    if editable {
        vec![
            EditItem::Cut,
            EditItem::Copy,
            EditItem::Paste,
            EditItem::SelectAll,
        ]
    } else if has_selection {
        vec![EditItem::Copy]
    } else {
        Vec::new()
    }
}

/// Pop the bar's right-click menu at the cursor. One command for every bar
/// appearance, called from `useBarDrag`.
///
/// The text items are AppKit's own (`cut:`, `copy:`, ...), sent down the
/// responder chain to the web view, so they act on its selection and AppKit
/// enables each one the way it does in any Mac text field. That needs the bar
/// to be the key window, so it is made key first when there are any.
#[tauri::command]
pub fn show_bar_context_menu(
    app: AppHandle,
    window: tauri::Window,
    editable: Option<bool>,
    has_selection: Option<bool>,
) -> Result<(), String> {
    let edit = edit_items_for(editable.unwrap_or(false), has_selection.unwrap_or(false));
    if !edit.is_empty() {
        if let Err(e) = window.set_focus() {
            warn!("Could not make the bar key for its text menu: {e}");
        }
    }
    let spec = bar_context_menu_spec(chat_toggle_label(active_chat_surface(&app)));
    let (menu, _items) =
        build_menu_with_edit_items(&app, &edit, &spec).map_err(|e| e.to_string())?;
    window.popup_menu(&menu).map_err(|e| e.to_string())
}

/// Create a state-aware tray menu with keyboard shortcuts
pub fn create_state_aware_tray_menu(
    app: &AppHandle,
) -> Result<TrayMenu, Box<dyn std::error::Error>> {
    info!("🍽️ Creating state-aware tray menu...");

    // Get keyboard shortcuts from app state
    let _shortcuts = match get_keyboard_shortcuts(app) {
        Ok(shortcuts) => shortcuts,
        Err(e) => {
            error!(
                "{} {}",
                prefixes::TRAY_MENU,
                format_error(templates::FAILED_TO_RETRIEVE, "keyboard shortcuts", e)
            );
            // Use defaults if we can't get from state
            crate::state::KeyboardShortcuts::default()
        }
    };

    let spec = tray_menu_spec(
        juno_row(active_chat_surface(app), bar_visible(app)).label(),
        false,
    );
    let (tray_menu, items) = build_menu_from_spec(app, &spec)?;
    let take = |id: &str| -> Result<MenuItem<tauri::Wry>, Box<dyn std::error::Error>> {
        items
            .iter()
            .find(|(item_id, _)| item_id == id)
            .map(|(_, item)| item.clone())
            .ok_or_else(|| format!("tray menu row {id} missing").into())
    };
    let status_item = take(tray_menu_ids::STATUS)?;
    let show_hide_item = take(tray_menu_ids::SHOW_HIDE)?;
    let talk_item = take(tray_menu_ids::TALK)?;

    info!("✅ State-aware tray menu created successfully");
    Ok(TrayMenu {
        menu: tray_menu,
        status_item,
        chat_toggle_item: show_hide_item,
        talk_item,
    })
}

/// Create and setup the system tray icon with dynamic state management
pub fn setup_tray_icon(app: &AppHandle) -> Result<(), Box<dyn std::error::Error>> {
    info!("🔧 Setting up system tray icon with dynamic state support...");

    let TrayMenu {
        menu: tray_menu,
        status_item,
        chat_toggle_item,
        talk_item,
    } = create_state_aware_tray_menu(app)?;

    // Load the idle frame. Template mode lets macOS tint it for the menu bar.
    let idle_frame = FRAMES_IDLE.first().ok_or("idle tray icon has no frames")?;
    let default_icon = load_tray_icon_from_data(idle_frame)?;

    let tray_icon = TrayIconBuilder::new()
        .menu(&tray_menu)
        .show_menu_on_left_click(false)
        .icon(default_icon)
        .icon_as_template(true)
        .tooltip(TrayIconState::Idle.tooltip())
        .on_tray_icon_event(|tray, event| {
            handle_tray_icon_event(tray.app_handle(), event);
        })
        .build(app)?;

    // Initialize the tray icon manager
    let app_handle = app.clone();
    tauri::async_runtime::spawn(async move {
        let manager = get_tray_icon_manager().await;
        let mut manager_guard = manager.lock().await;
        manager_guard.set_tray_icon(tray_icon);
        manager_guard.set_status_item(status_item);
        manager_guard.set_chat_toggle_item(chat_toggle_item);
        manager_guard.set_talk_item(talk_item);
        // Honour the saved "show tray icon" preference. Shown is the default,
        // so only a hidden icon needs applying.
        let visible = read_tray_icon_visible(&app_handle).await;
        if !visible {
            manager_guard.set_visible(false);
        }
        drop(manager_guard);

        // Start monitoring app state for tray icon updates
        setup_state_monitoring(&app_handle).await;
    });

    info!("✅ System tray icon setup completed with dynamic state support");
    Ok(())
}

/// Read an "is this subsystem active" event payload.
///
/// `None` means the payload was not a bool. These events used to be ignored
/// when that happened, which is how the icon got stranded: a stop path emitted
/// `agent-active` with an empty payload, the parse failed, and the handler
/// returned without touching the icon, so the menu bar kept animating an agent
/// that had finished. An unreadable payload still says something happened, so
/// every caller treats `None` the way it treats `false`: go and read the real
/// state rather than drop the event.
fn payload_is_active(payload: &str) -> Option<bool> {
    serde_json::from_str::<bool>(payload).ok()
}

/// Setup state monitoring to automatically update tray icon based on app state
async fn setup_state_monitoring(app_handle: &AppHandle) {
    info!("🔍 Setting up tray icon state monitoring...");

    let app_handle_clone = app_handle.clone();

    // Listen for various state change events.
    //
    // The two halves of the agent lifecycle arrive on two events now, and the
    // icon is the same for both: a person watching the menu bar wants to know
    // Juno is busy with them, not which phase it is in. What the split buys
    // here is that a `false` on either one no longer claims anything about the
    // other, so the recompute below can answer from both flags instead of
    // guessing which lifetime the payload belonged to.
    for agent_event in [
        crate::constants::events::agent::ACTIVE,
        crate::constants::events::agent::CAPTURE_ACTIVE,
    ] {
        let _ = app_handle.listen(agent_event, {
            let app_handle = app_handle_clone.clone();
            move |event| {
                let app_handle = app_handle.clone();
                let event = event.clone();
                tauri::async_runtime::spawn(async move {
                    let new_state = match payload_is_active(event.payload()) {
                        Some(true) => TrayIconState::Agent,
                        _ => determine_current_state(&app_handle).await,
                    };
                    update_tray_icon_state(new_state).await;
                });
            }
        });
    }

    // Listen for dictation state changes (both immediate and confirmed)
    let _ = app_handle.listen(crate::constants::events::dictation::ACTIVE, {
        let app_handle = app_handle_clone.clone();
        move |event| {
            let app_handle = app_handle.clone();
            let event = event.clone();
            tauri::async_runtime::spawn(async move {
                let new_state = match payload_is_active(event.payload()) {
                    Some(true) => TrayIconState::Recording,
                    _ => determine_current_state(&app_handle).await,
                };
                update_tray_icon_state(new_state).await;
            });
        }
    });

    // Listen for immediate dictation input state changes (when user presses/releases shortcut)
    let _ = app_handle.listen(crate::constants::events::dictation_state::INPUT_CHANGED, {
        let app_handle = app_handle_clone.clone();
        move |event| {
            let app_handle = app_handle.clone();
            tauri::async_runtime::spawn(async move {
                if let Ok(is_pressed) = serde_json::from_str::<bool>(event.payload()) {
                    let new_state = if is_pressed {
                        TrayIconState::Recording
                    } else {
                        determine_current_state(&app_handle).await
                    };
                    update_tray_icon_state(new_state).await;
                }
            });
        }
    });

    // Listen for immediate agent mode starts (when user presses agent shortcut)
    let _ = app_handle.listen(crate::constants::events::dictation::STARTED, {
        move |_event| {
            tauri::async_runtime::spawn(async move {
                // Set to Processing state initially, will change to AgentActive once agent actually starts
                update_tray_icon_state(TrayIconState::Transcribing).await;
            });
        }
    });

    // Listen for dictation completion events (when transcription finishes)
    let _ = app_handle.listen(crate::constants::events::dictation::FINISHED, {
        let app_handle = app_handle_clone.clone();
        move |event| {
            let app_handle = app_handle.clone();
            let event = event.clone();
            tauri::async_runtime::spawn(async move {
                // When dictation finishes, check if it's transitioning to agent mode
                // If there's a query payload, it means agent mode is starting
                if let Ok(payload) = serde_json::from_str::<serde_json::Value>(event.payload()) {
                    if payload.get("query").is_some() {
                        // Dictation finished and agent is about to start
                        update_tray_icon_state(TrayIconState::Transcribing).await;
                    } else {
                        // Just dictation finishing without agent mode
                        let new_state = determine_current_state(&app_handle).await;
                        update_tray_icon_state(new_state).await;
                    }
                } else {
                    // Fallback - just determine current state
                    let new_state = determine_current_state(&app_handle).await;
                    update_tray_icon_state(new_state).await;
                }
            });
        }
    });

    // Listen for agent-query-ready events (when agent mode voice transcription finishes)
    let _ = app_handle.listen(crate::constants::events::agent::QUERY_READY, {
        move |_event| {
            tauri::async_runtime::spawn(async move {
                // When agent voice transcription finishes, agent processing is about to start
                update_tray_icon_state(TrayIconState::Transcribing).await;
            });
        }
    });

    let _ = app_handle.listen(crate::constants::events::always_listening::MODE_CHANGED, {
        let app_handle = app_handle_clone.clone();
        move |event| {
            let app_handle = app_handle.clone();
            let event = event.clone();
            tauri::async_runtime::spawn(async move {
                let new_state = match payload_is_active(event.payload()) {
                    Some(true) => TrayIconState::Armed,
                    _ => determine_current_state(&app_handle).await,
                };
                update_tray_icon_state(new_state).await;
            });
        }
    });

    // Listen for floating bar state changes to detect processing states
    let _ = app_handle.listen(crate::constants::events::ui::BAR_STATE_CHANGED, {
        move |event| {
            tauri::async_runtime::spawn(async move {
                let event = event.clone();
                if let Ok(payload) = serde_json::from_str::<serde_json::Value>(event.payload()) {
                    if let Some(state) = payload.get("barState").and_then(|s| s.as_str()) {
                        let icon_state = match state {
                            "loading" | "transcribing" | "dictation_processing" => {
                                Some(TrayIconState::Transcribing)
                            }
                            "agent_thinking" => Some(TrayIconState::Agent),
                            "error" => Some(TrayIconState::Error),
                            _ => None,
                        };

                        if let Some(state) = icon_state {
                            update_tray_icon_state(state).await;
                        }
                    }
                }
            });
        }
    });

    // Listen for voice system errors
    let _ = app_handle.listen(crate::constants::events::dictation::ERROR, {
        let app_handle = app_handle_clone.clone();
        move |_event| {
            let app_handle = app_handle.clone();
            tauri::async_runtime::spawn(async move {
                update_tray_icon_state(TrayIconState::Error).await;

                // After a delay, reset to current state
                tokio::time::sleep(tokio::time::Duration::from_secs(3)).await;
                let new_state = determine_current_state(&app_handle).await;
                update_tray_icon_state(new_state).await;
            });
        }
    });

    // Listen for voice transcription errors
    let _ = app_handle.listen(crate::constants::events::voice_transcription::ERROR, {
        let app_handle = app_handle_clone.clone();
        move |_event| {
            let app_handle = app_handle.clone();
            tauri::async_runtime::spawn(async move {
                update_tray_icon_state(TrayIconState::Error).await;

                // After a delay, reset to current state
                tokio::time::sleep(tokio::time::Duration::from_secs(3)).await;
                let new_state = determine_current_state(&app_handle).await;
                update_tray_icon_state(new_state).await;
            });
        }
    });

    // The chat row's text follows the full-size window. Both of these events
    // come from `announce_main_window`, which every route that shows or hides
    // that window goes through, so listening here covers the bar's button, a
    // Dock click, the red X and the tray itself without knowing about any of
    // them.
    for event_name in [
        crate::constants::events::bar::MAIN_WINDOW_OPENED,
        crate::constants::events::bar::MAIN_WINDOW_CLOSED,
    ] {
        let _ = app_handle.listen(event_name, {
            let app_handle = app_handle_clone.clone();
            move |_event| {
                let app_handle = app_handle.clone();
                tauri::async_runtime::spawn(async move {
                    refresh_chat_toggle_label(&app_handle).await;
                });
            }
        });
    }

    info!("✅ Tray icon state monitoring setup completed");
}

/// Pick the icon that matches a set of live subsystems.
///
/// Split out from `determine_current_state` so the precedence is testable
/// without an `AppHandle`. Executing and capturing are two different lifetimes
/// of the agent and both show the Agent icon, so either one on its own is
/// enough: capture covers the microphone being open for a query, execution
/// covers the run that query starts, and a typed run has only the second.
/// Together they outrank everything else on purpose, because a capture
/// teardown landing while a run is still going must not drop the icon out of
/// Agent mid-run. Recomputing from the flags rather than from whichever
/// payload arrived is what makes that harmless.
fn tray_state_for(
    is_agent_executing: bool,
    is_agent_capturing: bool,
    is_dictation: bool,
    is_always_listening: bool,
) -> TrayIconState {
    if is_agent_executing || is_agent_capturing {
        return TrayIconState::Agent;
    }

    if is_dictation {
        return TrayIconState::Recording;
    }

    if is_always_listening {
        return TrayIconState::Armed;
    }

    TrayIconState::Idle
}

/// Determine the current tray icon state based on app state
async fn determine_current_state(app_handle: &AppHandle) -> TrayIconState {
    let app_state = app_handle.state::<AppState>();

    // Check states in order of priority
    let is_agent_executing = app_state.is_agent_executing();
    let is_agent_capturing = app_state.is_agent_capture_active();
    let is_dictation = app_state.is_dictation_active();
    let is_always_listening = app_state.get_always_listening_active().unwrap_or(false);

    info!(
        "🔍 Tray icon state check - Agent executing: {}, Agent capturing: {}, Dictation: {}, Always Listening: {}",
        is_agent_executing, is_agent_capturing, is_dictation, is_always_listening
    );

    let state = tray_state_for(
        is_agent_executing,
        is_agent_capturing,
        is_dictation,
        is_always_listening,
    );
    info!("Tray icon state resolved to {:?}", state);
    state
}

/// Update the tray icon state
